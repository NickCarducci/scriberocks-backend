//! Acceptance rocks from human judgments, per prose style:
//!   data/rocks/rocks_casual.tsv      from ProLex (learners' essays; TOEFL-11 via the ProLex repository)
//!   data/rocks/rocks_publishable.tsv from SWORDS (published prose; MASC)
//! Written to data/ (not committed: ProLex sentences are ETS-licensed TOEFL text).
//! Each rock is a real sentence; "offer" = substitutes people accepted, "never"
//! = ones they rejected — only substitutes WordNet links to the word (any
//! meaning), since the engine proposes from the dictionary. Entries are
//! lemma-matched ("w:" prefix, see rocks_eval). Test data only.
//!
//!   cargo run --release --example make_rocks [max per file]
use scribe::{text, Engine, Pos};
use std::collections::HashSet;
use std::path::Path;

fn members(e: &Engine, word: &str, pos: Option<Pos>) -> HashSet<String> {
    let mut out = HashSet::new();
    for p in pos.into_iter().chain([Pos::Noun, Pos::Verb, Pos::Adj, Pos::Adv]).take(if pos.is_some() { 1 } else { 4 }) {
        for l in e.lexicon.lemmatize(word, Some(p)) {
            for &s in e.lexicon.senses(&l, p) {
                out.extend(e.lexicon.synsets[s as usize].members.iter().filter(|m| !m.contains(' ')).map(|m| m.to_lowercase()));
            }
            out.remove(&l.to_lowercase());
        }
    }
    out
}

fn lemma(e: &Engine, w: &str) -> String {
    e.lexicon.lemmatize(w, None).into_iter().next().unwrap_or_else(|| w.to_lowercase()).to_lowercase()
}

fn line(rock: &str, offer: &[String], never: &[String]) -> String {
    let f = |v: &[String]| v.iter().map(|w| format!("w:{w}")).collect::<Vec<_>>().join("|");
    format!("{}\t{}\t{}", rock.replace('\t', " "), f(offer), f(never))
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let max: usize = std::env::args().nth(1).and_then(|v| v.parse().ok()).unwrap_or(150);
    let e = Engine::load(Path::new("models"))?;
    let list = |cell: &str| -> Vec<String> { cell.trim_matches(|c| c == '[' || c == ']').split(',').map(|s| s.trim().trim_matches(|c| c == '\'' || c == '"').to_lowercase()).filter(|s| !s.is_empty() && !s.contains(' ')).collect() };

    // ProLex → casual.
    let csv = std::fs::read_to_string("data/prolex/ProLex_v1.0_test.csv")?;
    let mut out = vec!["# Casual acceptance rocks from ProLex (learners' essays; human-judged substitutes, WordNet-linked only). Generated by examples/make_rocks.rs.".to_string()];
    let mut rows = Vec::new();
    let (mut field, mut row, mut quoted) = (String::new(), Vec::new(), false);
    let mut chars = csv.chars().peekable();
    while let Some(c) = chars.next() {
        match (c, quoted) {
            ('"', true) if chars.peek() == Some(&'"') => { field.push('"'); chars.next(); }
            ('"', _) => quoted = !quoted,
            (',', false) => row.push(std::mem::take(&mut field)),
            ('\n', false) => { row.push(std::mem::take(&mut field)); rows.push(std::mem::take(&mut row)); }
            ('\r', false) => {}
            _ => field.push(c),
        }
    }
    for r in rows.iter().skip(1).filter(|r| r.len() >= 4) {
        if out.len() > max { break }
        let target = r[0].to_lowercase();
        let rock = r[1].replace("**", "");
        let m = members(&e, &target, None);
        let offer: Vec<String> = list(&r[2]).into_iter().map(|w| lemma(&e, &w)).filter(|w| m.contains(w)).collect();
        let never: Vec<String> = list(&r[3]).into_iter().map(|w| lemma(&e, &w)).filter(|w| m.contains(w) && !offer.contains(w)).collect();
        if !offer.is_empty() || !never.is_empty() { out.push(line(&rock, &offer, &never)) }
    }
    std::fs::write("data/rocks/rocks_casual.tsv", out.join("\n") + "\n")?;
    println!("data/rocks/rocks_casual.tsv: {} rocks", out.len() - 1);

    // SWORDS → publishable (the sentence around each target; accepted > 50%, rejected = nobody accepted).
    let d: serde_json::Value = serde_json::from_str(&std::fs::read_to_string("data/swords/swords-v1.1_test.json")?)?;
    let mut by_target: std::collections::HashMap<&str, (Vec<String>, Vec<String>)> = std::collections::HashMap::new();
    for (sid, sub) in d["substitutes"].as_object().ok_or("no substitutes")? {
        let labels: Vec<&str> = d["substitute_labels"][sid].as_array().map(|a| a.iter().filter_map(|l| l.as_str()).filter(|l| *l != "UNSURE").collect()).unwrap_or_default();
        if labels.is_empty() { continue }
        let yes = labels.iter().filter(|l| l.starts_with("TRUE")).count() as f64 / labels.len() as f64;
        let w = sub["substitute"].as_str().unwrap_or("").to_lowercase();
        if w.contains(' ') { continue }
        let entry = by_target.entry(sub["target_id"].as_str().unwrap_or("")).or_default();
        if yes > 0.5 { entry.0.push(w) } else if yes == 0.0 { entry.1.push(w) }
    }
    let mut out = vec!["# Publishable acceptance rocks from SWORDS (published prose; human-rated substitutes, WordNet-linked only). Generated by examples/make_rocks.rs.".to_string()];
    let mut ids: Vec<&String> = d["targets"].as_object().ok_or("no targets")?.keys().collect();
    ids.sort();
    for tid in ids {
        if out.len() > max { break }
        let t = &d["targets"][tid];
        let ctx: Vec<char> = d["contexts"][t["context_id"].as_str().unwrap_or("")]["context"].as_str().unwrap_or("").chars().collect();
        let (off, word) = (t["offset"].as_u64().unwrap_or(0) as usize, t["target"].as_str().unwrap_or(""));
        let ends = |i: usize| ctx[i] == '\n' || (matches!(ctx[i], '.' | '!' | '?') && ctx.get(i + 1).is_none_or(|n| n.is_whitespace()));
        let start = (0..off.min(ctx.len())).rev().find(|&i| ends(i)).map_or(0, |i| i + 1);
        let end = (off + word.chars().count()..ctx.len()).find(|&i| ends(i)).map_or(ctx.len(), |i| i + 1);
        let rock: String = ctx[start..end].iter().collect::<String>().split_whitespace().collect::<Vec<_>>().join(" ");
        if text::tokenize(&rock).len() > 40 { continue }
        let pos = match t["pos"].as_str() { Some("NOUN") => Some(Pos::Noun), Some("VERB") => Some(Pos::Verb), Some("ADJ") => Some(Pos::Adj), Some("ADV") => Some(Pos::Adv), _ => None };
        let m = members(&e, &word.to_lowercase(), pos);
        let (acc, rej) = by_target.remove(tid.as_str()).unwrap_or_default();
        let offer: Vec<String> = acc.into_iter().filter(|w| m.contains(w)).collect();
        let never: Vec<String> = rej.into_iter().filter(|w| m.contains(w)).take(4).collect();
        if !offer.is_empty() || !never.is_empty() { out.push(line(&rock, &offer, &never)) }
    }
    std::fs::write("data/rocks/rocks_publishable.tsv", out.join("\n") + "\n")?;
    println!("data/rocks/rocks_publishable.tsv: {} rocks", out.len() - 1);
    Ok(())
}
